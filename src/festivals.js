// 接下来 7 天内的节日（倒计时用）
function festSoon(d = new Date()) {
  for (let i = 1; i <= 7; i++) {
    const day = new Date(d.getFullYear(), d.getMonth(), d.getDate() + i, 12);
    const f = festToday(day);
    if (f && f !== festToday(d)) return { fest: f, days: i };
  }
  return null;
}
