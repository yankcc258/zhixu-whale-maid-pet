// 季节（kind: 'season'）：闲着的时候偶尔换上（像看书、啃饭团那样），过一会儿换回来。
// 见过一次的衣服会收进 👘 衣柜，以后随时能换上。
// 日期都按电脑本地时间；春节和中秋按农历（用浏览器自带的农历日历算）。
const md = (d) => (d.getMonth() + 1) * 100 + d.getDate(); // 10 月 18 日 → 1018
const inRange = (d, a, b) => (a <= b ? md(d) >= a && md(d) <= b : md(d) >= a || md(d) <= b);
function lunar(d) {
  try {
    const p = new Intl.DateTimeFormat('en-u-ca-chinese', { month: 'numeric', day: 'numeric' }).formatToParts(d);
    const month = p.find((x) => x.type === 'month')?.value || '';
    return { leap: /bis|闰/i.test(month), month: parseInt(month, 10), day: parseInt(p.find((x) => x.type === 'day')?.value, 10) };
  } catch {
    return null;
  }
}
