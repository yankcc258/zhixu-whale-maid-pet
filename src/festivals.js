// d 是不是在表里那天的 a 到 b 天之后
function nearDay(table, d, a, b) {
  const t = table[d.getFullYear()];
  if (!t) return null;
  const [mm, dd] = t.split('-').map(Number),
    diff = Math.round((new Date(d.getFullYear(), d.getMonth(), d.getDate()) - new Date(d.getFullYear(), mm - 1, dd)) / 86400000);
  return diff >= a && diff <= b;
}
const lunarIs = (d, m, a, b) => {
  const l = lunar(d);
  return !!l && !l.leap && l.month === m && l.day >= a && l.day <= b;
};

